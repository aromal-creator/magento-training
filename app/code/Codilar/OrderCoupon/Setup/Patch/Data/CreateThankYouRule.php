<?php
declare(strict_types=1);

namespace Codilar\OrderCoupon\Setup\Patch\Data;

use Magento\Customer\Model\ResourceModel\Group\CollectionFactory as GroupCollectionFactory;
use Magento\Framework\App\Area;
use Magento\Framework\App\Config\Storage\WriterInterface;
use Magento\Framework\App\State;
use Magento\Framework\Setup\Patch\DataPatchInterface;
use Magento\SalesRule\Api\Data\RuleInterface;
use Magento\SalesRule\Api\Data\RuleInterfaceFactory;
use Magento\SalesRule\Api\RuleRepositoryInterface;
use Magento\SalesRule\Model\ResourceModel\Rule\CollectionFactory as RuleCollectionFactory;
use Magento\Store\Model\StoreManagerInterface;

/**
 * Creates the cart price rule the coupons belong to:
 * "Thank You - 10% Off Next Order", one use per coupon, codes auto-generated.
 * Its id is saved to config so the observer can find it.
 * (Marketing > Cart Price Rules - edit the discount or dates there.)
 */
class CreateThankYouRule implements DataPatchInterface
{
    public const RULE_NAME = 'Thank You - 10% Off Next Order';
    public const XML_PATH_RULE_ID = 'codilar_ordercoupon/general/rule_id';

    private RuleInterfaceFactory $ruleFactory;
    private RuleRepositoryInterface $ruleRepository;
    private RuleCollectionFactory $ruleCollectionFactory;
    private GroupCollectionFactory $groupCollectionFactory;
    private StoreManagerInterface $storeManager;
    private WriterInterface $configWriter;
    private State $appState;

    public function __construct(
        RuleInterfaceFactory $ruleFactory,
        RuleRepositoryInterface $ruleRepository,
        RuleCollectionFactory $ruleCollectionFactory,
        GroupCollectionFactory $groupCollectionFactory,
        StoreManagerInterface $storeManager,
        WriterInterface $configWriter,
        State $appState
    ) {
        $this->ruleFactory = $ruleFactory;
        $this->ruleRepository = $ruleRepository;
        $this->ruleCollectionFactory = $ruleCollectionFactory;
        $this->groupCollectionFactory = $groupCollectionFactory;
        $this->storeManager = $storeManager;
        $this->configWriter = $configWriter;
        $this->appState = $appState;
    }

    public function apply()
    {
        $this->appState->emulateAreaCode(Area::AREA_ADMINHTML, [$this, 'createRule']);

        return $this;
    }

    public function createRule(): void
    {
        $existing = $this->ruleCollectionFactory->create()
            ->addFieldToFilter('name', self::RULE_NAME)
            ->getFirstItem();

        if ($existing->getId()) {
            $ruleId = (int)$existing->getId();
        } else {
            $websiteIds = array_map(fn($w) => (int)$w->getId(), array_values($this->storeManager->getWebsites()));
            $groupIds = array_map('intval', $this->groupCollectionFactory->create()->getAllIds());

            $rule = $this->ruleFactory->create()
                ->setName(self::RULE_NAME)
                ->setDescription('Coupons are generated by Codilar_OrderCoupon after each order.')
                ->setIsActive(true)
                ->setWebsiteIds($websiteIds)
                ->setCustomerGroupIds($groupIds)
                ->setCouponType(RuleInterface::COUPON_TYPE_SPECIFIC_COUPON)
                ->setUseAutoGeneration(true)
                ->setUsesPerCoupon(1)
                ->setUsesPerCustomer(0)
                ->setSimpleAction(RuleInterface::DISCOUNT_ACTION_BY_PERCENT)
                ->setDiscountAmount(10)
                ->setStopRulesProcessing(false)
                ->setSortOrder(0);

            $ruleId = (int)$this->ruleRepository->save($rule)->getRuleId();
        }

        $this->configWriter->save(self::XML_PATH_RULE_ID, (string)$ruleId);
    }

    public static function getDependencies()
    {
        return [];
    }

    public function getAliases()
    {
        return [];
    }
}
